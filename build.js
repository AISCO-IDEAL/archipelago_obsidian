#!/usr/bin/env node
// Builds the plugin into dist/: main.js, manifest.json, styles.css. No dependencies: the modules are joined into one file.
//   node build.js [--install VAULT]    also copy it to VAULT/.obsidian/plugins/archipelago
'use strict';
const fs = require('fs');
const path = require('path');

const root = __dirname, dist = path.join(root, 'dist');
const read = f => fs.readFileSync(path.join(root, 'src', f), 'utf8');

// core, latex, fromlatex and richtext are UMD modules (Node's tests require them). In the bundle `module` would be
// Obsidian's, so each gets a scope of its own.
const umd = (name, file, deps) => `const ${name} = (() => { const module = undefined, self = { ${deps} }, exports = undefined;\n${read(file)}\nreturn self.${name}; })();\n`;
const main = [
  '/* Archipelago for Obsidian. Generated by build.js from src/. Do not edit. */',
  '"use strict";',
  umd('Core', 'core.js', ''), umd('Latex', 'latex.js', 'Core'), umd('FromLatex', 'fromlatex.js', 'Core, Latex'), umd('Rich', 'richtext.js', ''),
  `const APG_CSS = ${JSON.stringify(read('style.css'))};\n`,
  read('ui.js'), read('main.js'), read('overleaf.js'),
].join('\n');

fs.mkdirSync(dist, { recursive: true });
fs.writeFileSync(path.join(dist, 'main.js'), main);
fs.copyFileSync(path.join(root, 'manifest.json'), path.join(dist, 'manifest.json'));
fs.copyFileSync(path.join(root, 'src', 'styles.css'), path.join(dist, 'styles.css'));
console.log(`built dist (main.js ${(main.length / 1024).toFixed(0)} kB)`);

const i = process.argv.indexOf('--install');
if (i >= 0) {
  const vault = process.argv[i + 1];
  if (!vault || !fs.existsSync(path.join(vault, '.obsidian'))) { console.error('not an Obsidian vault: ' + vault); process.exit(2); }
  const target = path.join(vault, '.obsidian', 'plugins', 'archipelago');
  fs.mkdirSync(target, { recursive: true });
  for (const f of ['main.js', 'manifest.json', 'styles.css']) fs.copyFileSync(path.join(dist, f), path.join(target, f));
  console.log('installed in ' + target);
}
